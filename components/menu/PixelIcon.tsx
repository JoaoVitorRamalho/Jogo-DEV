export type IconName = keyof typeof ICONS;

function toPath(rows: readonly string[]): string {
  let d = "";
  rows.forEach((line, y) => {
    let x = 0;
    while (x < line.length) {
      if (line[x] !== "#") {
        x += 1;
        continue;
      }
      let end = x;
      while (line[end] === "#") end += 1;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(ICONS).map(([name, rows]) => [name, toPath(rows)])) as Record<IconName, string>;

export function PixelIcon({ name, className, style }: { name: IconName; className?: string; style?: CSSProperties }) {
  return (
    <svg className={className ? `px-icon ${className}` : "px-icon"} style={style} viewBox="0 0 9 9" shapeRendering="crispEdges" aria-hidden focusable="false">
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
}
