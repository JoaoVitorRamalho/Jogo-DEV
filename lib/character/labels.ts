export function labelItem(name: string): string {
  if (ITEM_NAMES[name]) return ITEM_NAMES[name];
  return name.replace(/[_]+/g, " ").replace(/([a-z])([A-Z])/g, "$1 $2");
}

export function labelColor(id: string): string {
  return COLOR_NAMES[id] ?? id.replace(/_/g, " ");
}

